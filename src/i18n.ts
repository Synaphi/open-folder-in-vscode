export function languageCodes(): string[] {
  return Object.keys(STRINGS);
}

export function canonicalLanguage(language: string): string {
  const tag = language.trim().replace(/_/g, "-").toLowerCase();
  if (STRINGS[tag]) return tag;
  if (tag === "zh-cn" || tag === "zh-hans" || tag === "zh-sg") return "zh";
  if (tag === "zh-hant" || tag === "zh-hk" || tag === "zh-mo") return "zh-tw";
  if (tag === "nb" || tag === "nb-no") return "no";
  if (tag === "pt-pt") return "pt";
  if (tag === "fil") return "tl";
  if (tag === "se") return "sv";
  const primary = tag.split("-")[0];
  if (primary && STRINGS[primary]) return primary;
  return "en";
}

export function translate(language: string, key: StringKey): string {
  const table = STRINGS[canonicalLanguage(language)] ?? STRINGS.en;
  return table[key] || STRINGS.en[key] || key;
}
